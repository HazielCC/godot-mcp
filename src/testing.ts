/**
 * Helpers for the testing tools that do not need Godot: reading a GDScript file to build a GUT test file, and
 * simple wildcard patterns for choosing scenes.
 */

export interface ScriptFunction {
  name: string;
  params: string;
  returns: string;
  isStatic: boolean;
}

export interface ParsedScript {
  className?: string;
  extendsName?: string;
  signals: string[];
  functions: ScriptFunction[];
}

/** The class name, parent class, signals and functions of a GDScript file. */
export function parseScript(text: string): ParsedScript {
  const parsed: ParsedScript = { signals: [], functions: [] };
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '');
    const className = /^class_name\s+(\w+)/.exec(line);
    if (className && !parsed.className) {
      parsed.className = className[1];
    }
    const parent = /^extends\s+("[^"]+"|[\w.]+)/.exec(line);
    if (parent && !parsed.extendsName) {
      parsed.extendsName = parent[1].replace(/"/g, '');
    }
    const signal = /^signal\s+(\w+)/.exec(line);
    if (signal) {
      parsed.signals.push(signal[1]);
    }
    const func = /^(static\s+)?func\s+(\w+)\s*\(([^)]*)\)\s*(?:->\s*([\w.[\]]+))?\s*:/.exec(line);
    if (func) {
      parsed.functions.push({ name: func[2], params: func[3].trim(), returns: func[4] ?? '', isStatic: func[1] !== undefined });
    }
  }
  return parsed;
}

const PLAIN_OBJECT_PARENTS = ['RefCounted', 'Object', 'Resource', 'Reference'];

/** True when the script can be created with new() and needs no tree: it extends RefCounted, Object or a Resource. */
function isPlainObject(parent: string | undefined): boolean {
  return parent !== undefined && (PLAIN_OBJECT_PARENTS.includes(parent) || /(Resource|Texture|Material|Shape|Mesh|Theme|Curve|Gradient)\d*D?$/.test(parent));
}

/** A GUT test file for a script. Public functions become pending tests; signals become checks that they exist. */
export function buildGutTest(scriptPath: string, parsed: ParsedScript): string {
  const plain = isPlainObject(parsed.extendsName);
  const publicFunctions = parsed.functions.filter((f) => !f.name.startsWith('_'));
  const lines: string[] = [
    'extends GutTest',
    `# Generated by godot-mcp for res://${scriptPath}.`,
    '# The tests marked pending() are waiting for you: replace each one with real checks.',
    '',
    `const Subject = preload("res://${scriptPath}")`,
    '',
    'var _sut',
    '',
    '',
    'func before_each():',
    plain ? '\t_sut = autofree(Subject.new())' : '\t_sut = Subject.new()\n\tadd_child_autofree(_sut)',
    '',
    '',
    'func test_can_be_created():',
    '\tassert_not_null(_sut)',
  ];
  for (const signal of parsed.signals) {
    lines.push('', '', `func test_has_signal_${signal}():`, `\tassert_has_signal(_sut, "${signal}")`);
  }
  const used = new Set<string>(['can_be_created']);
  for (const func of publicFunctions) {
    let name = func.name;
    while (used.has(name)) {
      name += '_';
    }
    used.add(name);
    const signature = `${func.isStatic ? 'static ' : ''}func ${func.name}(${func.params})${func.returns ? ` -> ${func.returns}` : ''}`;
    lines.push('', '', `func test_${name}():`, `\t# ${signature}`, `\tpending("Write the test for ${func.name}()")`);
  }
  return lines.join('\n') + '\n';
}

/** A regular expression for a pattern where * matches anything and ? one character. A pattern without wildcards matches anywhere. */
export function globToRegExp(pattern: string): RegExp {
  const escaped = pattern.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  if (!/[*?]/.test(pattern)) {
    return new RegExp(escaped);
  }
  return new RegExp(`^${escaped.replace(/\*/g, '.*').replace(/\?/g, '.')}$`);
}
